---@module 'hl'

-- Shared theme (palette + font) lives in ~/.config/theme, stowed from the theme package.
package.path = os.getenv("HOME") .. "/.config/?.lua;" .. package.path

hl.config({ autogenerated = false })

require("monitors")
require("look")
require("binds")

-- Environment variables, see https://wiki.hypr.land/Configuring/Environment-variables/
hl.env("XCURSOR_SIZE", 24)
hl.env("HYPRCURSOR_SIZE", 24)
hl.env("LIBVA_DRIVER_NAME", "nvidia")
hl.env("__GLX_VENDOR_LIBRARY_NAME", "nvidia")

-- Input, see https://wiki.hypr.land/Configuring/Variables/#input
hl.config({
  input = {
    kb_layout = "fr",
    kb_variant = "",
    kb_model = "",
    kb_options = "",
    kb_rules = "",
    follow_mouse = 1,
    sensitivity = 0, -- -1.0 - 1.0, 0 means no modification.
    touchpad = {
      natural_scroll = false,
    },
  },
})

-- Window rules, see https://wiki.hypr.land/Configuring/Window-Rules/

-- Ignore maximize requests from apps
hl.window_rule({
  name           = "suppress_event_maximize",
  match          = {
    class = ".*",
  },
  suppress_event = "maximize"
})

-- Fix some dragging issues with XWayland
hl.window_rule({
  name     = "no_focus_on",
  match    = {
    class = "pin 0",
  },
  no_focus = true
})

-- Autostart
hl.on("hyprland.start", function()
  hl.exec_cmd("waybar")
  hl.exec_cmd("swaync")
  hl.exec_cmd("hyprpaper")
end)
